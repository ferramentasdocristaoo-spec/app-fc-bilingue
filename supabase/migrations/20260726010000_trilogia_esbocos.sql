Lei: "Não adulterarás" - Jesus: Não cobiçar no coração Sobre os Juramentos (v.33-37):
Lei: Cumprir juramentos - Jesus: Seja o vosso falar sim, sim; não, não Sobre a Vingança (v.38-42):
Lei: "Olho por olho" - Jesus: Não resistir ao mal, dar a outra face Sobre o Amor (v.43-48):
Lei: "Amarás o teu próximo" - Jesus: Amai vossos inimigos
CONCLUSÃO
Mateus 5 estabelece os padrões do Reino dos Céus, que são radicalmente diferentes dos padrões mundanos. As bem-aventuranças descrevem o caráter dos cidadãos do reino, enquanto o restante do capítulo mostra como este caráter se manifesta na vida prática. Cristo não veio abolir a lei, mas cumprila e revelar seu verdadeiro significado. Que possamos buscar viver segundo estes princípios elevados, dependendo da graça de Deus para alcançar esta justiça superior.

