Os Dez Mandamentos
TEXTO BASE: Êxodo 20
INTRODUÇÃO
Êxodo 20 registra a entrega dos Dez Mandamentos no Monte Sinai, um dos momentos mais significativos da história da humanidade. Este capítulo estabelece os princípios morais fundamentais que governam o relacionamento do homem com Deus e com seu próximo. O contexto histórico mostra Israel recém-liberto do Egito, recebendo a lei que os distinguiria como povo de Deus. A relevância destes mandamentos transcende o tempo e a cultura, estabelecendo padrões morais universais que refletem o caráter santo de Deus.
EXPOSIÇÃO:
I. O PREÂMBULO (versículos 1-2)
V.1 - A autoridade divina: "E falou Deus todas estas palavras" V.2 - A base da lei: "Eu sou o Senhor teu Deus, que te tirei da terra do Egito" relacionamento baseado na redenção II. DEVERES PARA COM DEUS (versículos 3-11) Primeiro Mandamento (v.3):
"Não terás outros deuses diante de mim" - Monoteísmo exclusivo
Deus exige adoração exclusiva e supremacia absoluta Segundo Mandamento (v.4-6):
"Não farás imagem de escultura" - Proibição da idolatria
Deus é espírito e deve ser adorado em espírito e verdade Terceiro Mandamento (v.7):
"Não tomarás o nome do Senhor teu Deus em vão" - Reverência ao nome divino
O nome de Deus deve ser tratado com santidade e respeito Quarto Mandamento (v.8-11):
"Lembra-te do dia do sábado, para o santificar" - Santificação do tempo
Princípio do descanso e adoração regular
III. DEVERES PARA COM O PRÓXIMO (versículos 12-17) Quinto
Mandamento (v.12):
"Honra a teu pai e a tua mãe" - Respeito à autoridade familiar
Base da ordem social e promessa de longevidade Sexto Mandamento (v.13):
"Não matarás" - Santidade da vida humana
Proteção do direito fundamental à vida Sétimo Mandamento (v.14):
"Não adulterarás" - Santidade do casamento
Proteção da instituição familiar Oitavo Mandamento (v.15):
