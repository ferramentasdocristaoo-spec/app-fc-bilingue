"Bem-aventurados os que choram" - Tristeza pelo pecado e sofrimento
"Porque eles serão consolados" - Promessa de consolo divino Terceira Bem-aventurança (v.5):
"Bem-aventurados os mansos" - Força sob controle, humildade
"Porque eles herdarão a terra" - Promessa de herança futura Quarta Bem-aventurança (v.6):
"Bem-aventurados os que têm fome e sede de justiça" - Desejo intenso pela retidão
"Porque eles serão fartos" - Satisfação garantida Quinta Bem-aventurança (v.7):
"Bem-aventurados os misericordiosos" - Compaixão ativa pelos outros
"Porque eles alcançarão misericórdia" - Reciprocidade da misericórdia Sexta Bem-aventurança (v.8):
"Bem-aventurados os limpos de coração" - Pureza interior genuína
"Porque eles verão a Deus" - Visão beatífica prometida Sétima Bem-aventurança (v.9):
"Bem-aventurados os pacificadores" - Promotores ativos da paz
"Porque eles serão chamados filhos de Deus" - Reconhecimento da filiação divina Oitava Bemaventurança (v.10-12):
"Bem-aventurados os que sofrem perseguição" - Sofrimento por causa da justiça
"Porque deles é o reino dos céus" - Mesma promessa da primeira bem-aventurança
