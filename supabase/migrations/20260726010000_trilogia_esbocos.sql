V.13 - "Vós sois o sal da terra" - Função preservadora e tempero dos cristãos
V.14-15 - "Vós sois a luz do mundo" - Função iluminadora dos discípulos
V.16 - "Assim resplandeça a vossa luz" - Propósito: glorificar o Pai
