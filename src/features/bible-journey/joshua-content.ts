const sectionOf = (number: number) => number <= 5 ? "commission" : number <= 12 ? "conquest" : number <= 21 ? "inheritance" : "renewal";

export function buildJoshuaChapters(): JourneyChapter[] {
  return Array.from({ length: 24 }, (_, index) => {
    const number = index + 1;
    const content = Object.fromEntries((Object.keys(titles) as JourneyLanguage[]).map(language => [language, {
      title: titles[language][index], description: descriptions[language][index], reflectionPrompt: prompts[language],
    }])) as JourneyChapter["content"];
    return { number, sectionSlug: sectionOf(number), content };
  });
}
